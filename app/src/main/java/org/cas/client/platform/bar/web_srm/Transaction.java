package org.cas.client.platform.bar.web_srm;

import java.util.ArrayList;
import java.util.List;

public class Transaction{
    // Field identifying the business's sector of activity.
    public TransactionSectActi sectActi;

    // Field giving the address of the business named on the document.
    public TransactionDocAdr docAdr;

    // Information regarding the custumer that acquires a paid or payable supply.
    public TransactionClint clint;

    // List of transaction items
    public List<TransactionItem> lstItems;

    // List of transactions referenced by this one
    public List<TransactionReference> lsttransactionReferences;

    // Field identifying the digital signatures generated by your SRS for the transaction
    public TransactionSigna signa;
    
    // Adjustment amount applied on the total( e.g. rounding, coupon, gift card, discount).
    public String Ajus;

    // Amount for the supply after taxes is the sum of the avantTax, TPS and TVQ fields
    public String ApresTax;

    // Amount before taxes is comprised of the sum of the prix field of each item and each detail.
    public String AvantTax;
    public String CommerceElectronique;// E-commerce indicator
    public String CodCertif;// Code issued by us proving that the SRS is certified and can communicate with the WEB-SRM.
    public String DatTrans;// Time of the transaction to which the bill refers
    
    public String EmprCertifSEV;	// Thumbprint of the certificate containing the public key linked to the private key
    								// used to produce the current transaction signature( actu)
    public String FormImpr;// Document print option (Paper, Electronic, ...)
    public String IdPartn;// Unique identifier issued by us for the partner ( you as an SRS developer).
    public String IdSev; // Unique identifier issued by us for the name of the SRS
    public String IdVersi;// Unique identifier issued by us for the version of the SRS.
    public String ModImpr;// Print mode for the document. (Bill, Reproduction, Duplicata, ...)
    public String ModPai;// Method of payment used for the bill.
    public String ModTrans;// Transaction mode (Operation or Training)
    public String MTDU;// The amount due after adjusting the after tax amount.
    public String NoDossFO;// The mandatory billing file number.

    // Usual name of the mandatary who operates the business.
    public String NomMandt;

    // Name of the user who produced the customer’s bill.
    public String NomUtil;

    // Number identifying the transaction to which the document refers.
    public String NoTrans;

    // Mandatary’s GST registration number
    public String NoTPS;

    // Mandatary’s QST registration number
    public String NoTVQ;

    // The amount of the tip.
    public String Pourb;

    // The type of business relationship.
    public String RelaCommer;

    // The balance of the amount payable (the value of the apresTax field minus the sum of the amounts in the versActu and versAnt fields)
    public String Solde;

    // GST paid or payable on the supply.
    public String TPS;

    // QST paid or payable on the supply.
    public String TVQ;

    // Transaction type. Possible values are: ADDI (temporary bill), ESTM (estimate), RFER (closing receipt), SOUM (quote), TIER (occasional third party), SOB (n/a)
    public String TypTrans;

    // Coordinated Universal Time used by the SRS when recording the date transaction( datTrans)
    public String Utc;

    // Amount of the current payment.
    public String VersActu;

    // The amount of previous payments (excluding the current payment).
    public String VersAnt;

    // SRS/POS version assigned by the developer and corresponding to the update of the parent version (versiParn)
    public String Versi;

    // Parent version of the SRS. This number is assigned by the developer.
    public String VersiParn;

    // Constructeurs
    public Transaction( ){
        sectActi = new TransactionSectActi( );
        docAdr = new TransactionDocAdr( );
        clint = new TransactionClint( );
        signa = new TransactionSigna( );
        lsttransactionReferences = new ArrayList<TransactionReference>( );
    }

    // Returns the content of the transaction in a json document
    // <returns>json document</returns>
    public String GetJson(){
        StringBuilder s = new StringBuilder( );

        s.append( "\"sectActi\": {" );
        s.append( "\"abrvt\": \"").append(sectActi.Abrvt );
        s.append( "\",\"typServ\": \"").append(sectActi.TypServ );
        s.append( "\",\"noTabl\": \"").append(sectActi.NoTabl );
        s.append( "\",\"nbClint\": \"").append(sectActi.NbClint );
        s.append( "\"}," );
        s.append( "\"noTrans\": \"").append(NoTrans );
        s.append( "\",\"nomMandt\": \"").append(NomMandt );
        s.append( "\",\"nomUtil\": \"").append(NomUtil );

        if(( docAdr.DocNoCiviq != null && docAdr.DocNoCiviq.length() > 0 )
        		|| ( docAdr.DocCodePostal != null && docAdr.DocCodePostal.length() > 0 )){
            s.append( "\",\"docAdr\": {" );
            s.append( "\"docNoCiviq\": \"").append(docAdr.DocNoCiviq ).append("\",");
            s.append( "\"docCp\": \"").append(docAdr.DocCodePostal ).append("\"");
            s.append( "}," );
        }
        if( RelaCommer != null && RelaCommer.length() > 0 )
            s.append( "\"relaCommer\": \"").append(RelaCommer ).append("\",");

        if(( clint.NomClint != null && clint.NomClint.length() > 0)
        	|| (clint.NoTvqClint != null && clint.NoTvqClint.length() > 0) 
        	|| ( clint.Tel1 != null && clint.Tel1.length() > 0) 
        	|| ( clint.Tel2 != null && clint.Tel2.length() > 0) 
        	|| ( clint.Courl != null && clint.Courl.length() > 0) ){
        	
            s.append( "\"clint\": {" );
            s.append( "\"nomClint\": \"").append(clint.NomClint ).append("\",");
            s.append( "\"noTvqClint\": \"").append(clint.NoTvqClint ).append("\",");
            s.append( "\"tel1\": \"").append(clint.Tel1 ).append("\",");
            s.append( "\"tel2\": \"").append(clint.Tel2 ).append("\",");
            s.append( "\"courl\": \"").append(clint.Courl ).append("\",");

            if( clint.lstAdrClients.size() > 0 ){
                s.append( ",\"adr\": [" );
                for( int i = 0; i < clint.lstAdrClients.size(); i++ )
                {
                    s.append( clint.lstAdrClients.get(i).GetJson( ) );

                    if( i < clint.lstAdrClients.size() - 1 )
                        s.append( "," );
                }
                s.append( "]," );
            }
            s.append( "}," );
        }
        s.append( "\"datTrans\": \"").append(DatTrans ).append("\",");
        s.append( "\"utc\": \"").append(Utc ).append("\",");

        // items
        if( lstItems.size() > 0 ){
            s.append( "\"items\": [ " );

            for( int i = 0; i < lstItems.size(); i++ ){
                s.append( lstItems.get(i).GetJson( ) );
                if( i < lstItems.size() - 1 )
                    s.append( "," );
            }
            s.append( "]," );
        }
        
        s.append( "\"mont\": {" );
        s.append( "\"avantTax\": \"").append(AvantTax );
        s.append( "\",\"TPS\": \"").append(TPS );
        s.append( "\",\"TVQ\": \"").append(TVQ );
        s.append( "\",\"apresTax\": \"").append(ApresTax );
//        s.append( "\",\"versActu\": \"").append(VersActu );
//        s.append( "\",\"versAnt\": \"").append(VersAnt );
//        s.append( "\",\"sold\": \"").append(Solde );
        s.append( "\",\"ajus\": \"").append(Ajus );
        s.append( "\",\"mtdu\": \"").append(MTDU );
        s.append( "\",\"pourb\": \"").append(Pourb );
        s.append( "\"}," );
        s.append( "\"noDossFO\": \"").append(NoDossFO ).append("\",");
        s.append( "\"noTax\": {" );
        s.append( "\"noTPS\": \"").append(NoTPS ).append("\",");
        s.append( "\"noTVQ\": \"").append(NoTVQ ).append("\"");
        s.append( "}," );
        s.append( "\"commerElectr\": \"").append(CommerceElectronique ).append("\",");
        s.append( "\"typTrans\": \"").append(TypTrans ).append("\",");
        s.append( "\"modPai\": \"").append(ModPai ).append("\",");
        s.append( "\"modImpr\": \"").append(ModImpr ).append("\",");
        s.append( "\"formImpr\": \"").append(FormImpr ).append("\",");
        s.append( "\"modTrans\": \"").append(ModTrans ).append("\",");
        s.append( "\"signa\": {" );
        s.append( "\"datActu\": \"").append(signa.DatActu ).append("\",");
        s.append( "\"actu\": \"").append(signa.Actu ).append("\",");
        s.append( "\"preced\": \"").append(signa.Preced ).append("\"");
        s.append( "}," );

        // Références
        if( lsttransactionReferences.size() > 0 ){
            s.append( "\"refs\": [ " );
            for( int i = 0; i < lsttransactionReferences.size(); i++ ){
                s.append( lsttransactionReferences.get(i).GetJson( ) );

                if( i < lsttransactionReferences.size() - 1 )
                    s.append( "," );
            }
            s.append( "]," );
        }

        s.append( "\"emprCertifSEV\": \"").append(EmprCertifSEV ).append("\",");
        s.append( "\"SEV\": {" );
        s.append( "\"idSEV\": \"").append(IdSev ).append("\",");
        s.append( "\"idVersi\": \"").append(IdVersi ).append("\",");
        s.append( "\"codCertif\": \"").append(CodCertif ).append("\",");
        s.append( "\"idPartn\": \"").append(IdPartn ).append("\",");
        s.append( "\"versi\": \"").append(Versi ).append("\",");
        s.append( "\"versiParn\": \"").append(VersiParn ).append("\"");
        s.append( "}" );

        return s.toString( );
    }
}