public class MovingPlanCheck {
    static void check(boolean condition, String message) { if (!condition) throw new AssertionError(message); }
    static JSONObject row(JSONObject draft, int id) {
        JSONArray rows = draft.getJSONArray("rows");
        for (int i = 0; i < rows.length(); i++) if (rows.getJSONObject(i).getInt("productId") == id) return rows.getJSONObject(i);
        throw new AssertionError("Missing product " + id);
    }
    static int scalar(Connection db, String sql) throws Exception {
        try (Statement s = db.createStatement(); ResultSet rs = s.executeQuery(sql)) { rs.next(); return rs.getInt(1); }
    }
    public static void main(String[] args) throws Exception {
        Class.forName("org.hsqldb.jdbc.JDBCDriver");
        try (Connection db = DriverManager.getConnection("jdbc:hsqldb:mem:phone_moving", "SA", "")) {
            try (Statement s = db.createStatement()) {
                s.execute("CREATE TABLE PRODUCT(ID INT PRIMARY KEY,CODE VARCHAR(40),MNEMONIC VARCHAR(100),SUBJECT VARCHAR(100),CATEGORY VARCHAR(40),DELETED INT,STOCK1 INT,STOCK2 INT,STOCK3 INT,STOCK1_SHORTAGE INT,CASE_QTY INT)");
                s.execute("INSERT INTO PRODUCT VALUES(1,'a','ALPHA 5c 355x12','ALPHA 5c 355x12','BIERE',0,0,0,5,-2,NULL),"
                        + "(2,'a6','ALPHA 5c 355x6','ALPHA 5c 355x6','BIERE',0,0,0,4,-1,NULL),"
                        + "(3,'b','BETA 5c 740','BETA 5c 740','BIERE',0,0,0,36,-24,NULL),"
                        + "(4,'c','GAMMA 5c 355x12','GAMMA 5c 355x12','BIERE',0,0,0,3,0,NULL),"
                        + "(5,'d','DELTA 5c 355x12','DELTA 5c 355x12','BIERE',0,0,0,3,10,NULL),"
                        + "(6,'e','OTHER','OTHER','TABAC',0,0,0,100,-100,NULL)");
                s.execute("CREATE TABLE BILL(ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,CREATETIME VARCHAR(255),OPENTIME VARCHAR(255),TABLEID VARCHAR(255),BILLINDEX VARCHAR(255),CUSTOMERID INT,STATUS INT,TOTAL INT,DISCOUNT INT,SERVICEFEE INT,COMMENT VARCHAR(255),PLAN_NOTE LONGVARCHAR,EMPLOYEEID INT)");
                s.execute("CREATE TABLE OUTPUT(ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,SUBJECT VARCHAR(255),CONTACTID VARCHAR(255),PRODUCTID INT,AMOUNT INT,TOTALPRICE INT,DISCOUNT INT,CONTENT LONGVARCHAR,EMPLOYEEID INT,TIME VARCHAR(255),CATEGORY VARCHAR(255),FOLDERID INT,DELETED INT)");
                s.execute("INSERT INTO BILL(ID,STATUS) VALUES(100,60)");
                s.execute("INSERT INTO OUTPUT(PRODUCTID,AMOUNT,TIME,FOLDERID,DELETED) VALUES(4,2,'" + LocalDate.now().minusDays(1) + " 12:00:00',100,60)");
            }
            db.createStatement().execute("CREATE TABLE EMPLOYEE(ID INT PRIMARY KEY)"); db.createStatement().execute("INSERT INTO EMPLOYEE VALUES(1)"); MobileMovingStore.ensureSchema(db); MobileMovingStore.ensureSchema(db);
            JSONObject input = MobileMovingStore.inputs(db);
            JSONObject draft = MovingPlan.generate(input, null);
            check(draft.getJSONArray("rows").length() == 3, "Eligible groups and sales floor");
            check(row(draft,1).getInt("cases") == 2, "12-pack priority and aggregated MANQUE");
            check(row(draft,3).getInt("units") == 24, "740ml case is 12 sale units");
            check(row(draft,4).getInt("cases") == 1, "Most recent sales day floor");
            check(scalar(db,"SELECT COUNT(*) FROM BILL") == 1, "Generating a phone plan must not create a POS plan");
            JSONObject edited = new JSONObject(draft.toString());
            row(edited,3).put("cases",1).put("units",12).put("manualQuantity",true);
            JSONObject reopened = MovingPlan.generate(input, new JSONObject(edited.toString()));
            check(row(reopened,3).getInt("cases") == 1 && row(reopened,3).getInt("units") == 12,
                    "Manual case quantity survives persistence and regeneration");
            check(row(MovingPlan.command(input,reopened),3).getInt("units") == 12,
                    "Submission uses manually edited units");
            row(draft,1).put("state","done"); row(draft,3).put("state","skipped");
            String saved = draft.toString();
            db.createStatement().execute("UPDATE PRODUCT SET STOCK1_SHORTAGE=-5 WHERE ID=1");
            db.createStatement().execute("UPDATE PRODUCT SET STOCK1_SHORTAGE=-36 WHERE ID=4");
            JSONObject latest = MobileMovingStore.inputs(db);
            draft = MovingPlan.generate(latest, new JSONObject(saved));
            check(row(draft,1).getInt("cases") == 2 && row(draft,1).getString("state").equals("done"), "Completed units survive restart and stock change");
            check(row(draft,3).getString("state").equals("skipped"), "Exclusion survives regeneration");
            check(row(draft,4).getInt("cases") == 3, "Pending quantity recalculates and caps at basement stock");
            JSONObject request = MovingPlan.command(latest,draft);
            int stockBefore = scalar(db,"SELECT STOCK3 FROM PRODUCT WHERE ID=1");
            try { MobileMovingStore.submit(db,request,(c,id,n) -> { throw new SQLException("Injected shortage failure"); },1); throw new AssertionError("Expected rollback"); }
            catch (SQLException expected) {}
            check(scalar(db,"SELECT STOCK3 FROM PRODUCT WHERE ID=1") == stockBefore, "Stock rollback");
            check(scalar(db,"SELECT COUNT(*) FROM BILL") == 1 && scalar(db,"SELECT COUNT(*) FROM MOBILE_MOVING_RECEIPT") == 0, "Plan and receipt rollback");
            db.createStatement().execute("UPDATE PRODUCT SET STOCK1_SHORTAGE=-2 WHERE ID=2");
            try { MobileMovingStore.submit(db,request,Cmd_OpenDrawer::applyMovedBottlesToShortage,1); throw new AssertionError("Accepted stale sibling MANQUE"); }
            catch (InventoryCommandServer.BusyException expected) {}
            latest = MobileMovingStore.inputs(db); request = MovingPlan.command(latest,draft);
            JSONObject result = MobileMovingStore.submit(db,request,Cmd_OpenDrawer::applyMovedBottlesToShortage,1);
            int bill = result.getInt("billId");
            check(scalar(db,"SELECT STOCK3 FROM PRODUCT WHERE ID=1") == 3 && scalar(db,"SELECT STOCK1 FROM PRODUCT WHERE ID=1") == 2,"Completed stock transfer");
            check(scalar(db,"SELECT STOCK1_SHORTAGE FROM PRODUCT WHERE ID=1") == -3,"Desktop MANQUE payback reused");
            check(scalar(db,"SELECT STOCK3 FROM PRODUCT WHERE ID=3") == 36,"Skipped stock unchanged");
            check(scalar(db,"SELECT STOCK3 FROM PRODUCT WHERE ID=4") == 0,"All remaining rows completed");
            check(scalar(db,"SELECT STATUS FROM BILL WHERE ID="+bill) == 61,"Saved completed moving plan");
            check(scalar(db,"SELECT COUNT(*) FROM OUTPUT WHERE FOLDERID="+bill) == 2,"Only moved rows saved as output; exclusions audited in plan note");
            JSONObject retry = MobileMovingStore.submit(db,new JSONObject(request.toString()),Cmd_OpenDrawer::applyMovedBottlesToShortage,1);
            check(retry.getInt("billId") == bill && scalar(db,"SELECT STOCK1 FROM PRODUCT WHERE ID=1") == 2,"Identical retry exactly once");
            check(scalar(db,"SELECT COUNT(*) FROM BILL") == 2,"No duplicate plan");
            JSONObject wrong = new JSONObject(request.toString()); row(wrong,1).put("cases",3).put("units",3);
            try { MobileMovingStore.submit(db,wrong,Cmd_OpenDrawer::applyMovedBottlesToShortage,1); throw new AssertionError("Reused ID with changed payload"); }
            catch (IllegalArgumentException expected) {}
            try (InventoryCommandServer server = new InventoryCommandServer(0, c -> 1, null,
                    (id, body) -> body == null ? MobileMovingStore.inputs(db) : MobileMovingStore.submit(db,body,Cmd_OpenDrawer::applyMovedBottlesToShortage,1))) {
                java.net.HttpURLConnection c = (java.net.HttpURLConnection)new java.net.URL("http://127.0.0.1:"+server.getPort()+"/AikaPos/movingDraft").openConnection();
                check(c.getResponseCode()==200,"HTTP input endpoint"); c.disconnect();
                c = (java.net.HttpURLConnection)new java.net.URL("http://127.0.0.1:"+server.getPort()+"/AikaPos/movingDraft").openConnection();
                c.setRequestMethod("POST"); c.setDoOutput(true); c.setRequestProperty("Content-Type","application/json");
                try (java.io.OutputStream out=c.getOutputStream()) { out.write(request.toString().getBytes("UTF-8")); }
                check(c.getResponseCode()==200,"HTTP identical retry"); c.disconnect();
            }
        }
        System.out.println("PASS: local generation, desktop units/sales/MANQUE rules, saved decisions, recalculation, rollback, conflicts, POS history, idempotency, HTTP.");
    }
}
